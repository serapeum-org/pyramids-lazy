"""Tests for `ci/parquet-plugin/extract_cpl_config.py`.

`cpl_config.h` is generated by GDAL's cmake configure, so a release source tarball does not
carry it and compiling the standalone driver fails at the first `#include "cpl_config.h"`. It
records ~40 platform probe results, among them `SIZEOF_VOIDP` and the `VSI_*64` large-file
macros, which decide struct layouts the plugin shares with libgdal -- so the header is taken
from a real GDAL build of the same version rather than written by hand, and the extractor
asserts the macros are present rather than assuming a downloaded package is the right one.

A `.conda` package is a zip holding zstd-compressed tarballs. The fixtures here build one from
scratch, which keeps the tests offline and lets the malformed cases exist at all.
"""

from __future__ import annotations

import importlib.util
import io
import sys
import tarfile
import zipfile
from pathlib import Path

import pytest

pytestmark = pytest.mark.core

CI_DIR = Path(__file__).resolve().parents[2] / "ci" / "parquet-plugin"


def _load() -> object:
    """Import the extractor from its path, since `ci/` is not an importable package."""
    path = CI_DIR / "extract_cpl_config.py"
    key = "_ci_parquet_plugin_extract_cpl_config"
    spec = importlib.util.spec_from_file_location(key, path)
    assert spec is not None and spec.loader is not None, f"cannot load {path}"
    module = importlib.util.module_from_spec(spec)
    sys.modules[key] = module
    spec.loader.exec_module(module)
    return module


extract_mod = _load()

_HEADER = """/* generated */
#define SIZEOF_INT 4
#define SIZEOF_UNSIGNED_LONG 8
#define SIZEOF_VOIDP 8
#define SIZEOF_SIZE_T 8
#define SIZEOF_LONG_INT 8
#define VSI_STAT64_T stat64
#define VSI_STAT64 stat64
#define HAVE_MMAP 1
"""


def _zstd_compress(data: bytes) -> bytes:
    """Compress with whichever zstd encoder this interpreter has.

    Returns:
        bytes: The compressed stream.
    """
    try:
        from compression import zstd  # noqa: PLC0415

        return zstd.compress(data)
    except ImportError:
        pass
    zstandard = pytest.importorskip(
        "zstandard", reason="zstd encoder unavailable on this machine"
    )
    return zstandard.ZstdCompressor().compress(data)


def _conda_package(path: Path, members: dict[str, str], prefix: str = "pkg-") -> Path:
    """Write a `.conda`-shaped archive carrying `members`.

    Args:
        path: Where to write the package.
        members: Archive paths mapped to their text contents.
        prefix: Name prefix for the inner tarball; override to forge a malformed package.

    Returns:
        pathlib.Path: `path`.
    """
    inner = io.BytesIO()
    with tarfile.open(fileobj=inner, mode="w") as tf:
        for name, text in members.items():
            payload = text.encode()
            info = tarfile.TarInfo(name)
            info.size = len(payload)
            tf.addfile(info, io.BytesIO(payload))
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("metadata.json", "{}")
        zf.writestr(f"{prefix}libgdal-core.tar.zst", _zstd_compress(inner.getvalue()))
    return path


class TestExtraction:
    """The happy path, which is what unblocks the compile."""

    def test_the_generated_header_is_written(self, tmp_path: Path):
        """Without this header every GDAL source fails at `#include "cpl_config.h"`."""
        package = _conda_package(
            tmp_path / "p.conda", {"include/cpl_config.h": _HEADER}
        )

        written = extract_mod.extract(package, tmp_path / "inc")

        assert written == tmp_path / "inc" / "cpl_config.h"
        assert "#define SIZEOF_VOIDP 8" in written.read_text()

    def test_other_members_are_ignored(self, tmp_path: Path):
        """The package also ships binaries, none of which may reach the wheel."""
        package = _conda_package(
            tmp_path / "p.conda",
            {
                "lib/libgdal.so.39": "ELF",
                "include/cpl_config.h": _HEADER,
                "include/gdal.h": "/* unused here */",
            },
        )

        extract_mod.extract(package, tmp_path / "inc")

        assert sorted(p.name for p in (tmp_path / "inc").iterdir()) == ["cpl_config.h"]


class TestRejections:
    """A wrong or truncated package must stop the build, not produce a half-header."""

    def test_a_package_without_the_header_is_refused(self, tmp_path: Path):
        """conda-forge could split the headers into another package at any time."""
        package = _conda_package(tmp_path / "p.conda", {"lib/libgdal.so.39": "ELF"})

        with pytest.raises(SystemExit, match="cpl_config.h"):
            extract_mod.extract(package, tmp_path / "inc")

    def test_an_archive_with_no_payload_member_is_refused(self, tmp_path: Path):
        """A `.conda` always has a `pkg-*` member; anything else is not one."""
        package = _conda_package(
            tmp_path / "p.conda", {"include/cpl_config.h": _HEADER}, prefix="info-"
        )

        with pytest.raises(SystemExit, match="not a .conda package"):
            extract_mod.extract(package, tmp_path / "inc")

    @pytest.mark.parametrize(
        "dropped", ["SIZEOF_VOIDP", "VSI_STAT64_T", "SIZEOF_SIZE_T"]
    )
    def test_a_header_missing_an_abi_macro_is_refused(self, tmp_path: Path, dropped):
        """These decide struct layouts shared with libgdal, so absence is not survivable.

        Test scenario:
            A header for the wrong architecture, or a truncated one, would otherwise compile
            and then disagree with libgdal at runtime -- the failure this whole indirection
            exists to prevent.
        """
        trimmed = "\n".join(
            line
            for line in _HEADER.splitlines()
            if not line.startswith(f"#define {dropped} ")
        )
        package = _conda_package(
            tmp_path / "p.conda", {"include/cpl_config.h": trimmed}
        )

        with pytest.raises(SystemExit, match=dropped):
            extract_mod.extract(package, tmp_path / "inc")

    def test_a_prefix_of_a_macro_name_does_not_satisfy_the_check(self, tmp_path: Path):
        """`VSI_STAT64` is a prefix of `VSI_STAT64_T`, so a prefix test would accept a gap."""
        trimmed = "\n".join(
            line
            for line in _HEADER.splitlines()
            if not line.startswith("#define VSI_STAT64 ")
        )
        package = _conda_package(
            tmp_path / "p.conda", {"include/cpl_config.h": trimmed}
        )

        with pytest.raises(SystemExit, match="VSI_STAT64"):
            extract_mod.extract(package, tmp_path / "inc")


class TestZstdDecoder:
    """The two decoders, and the message when neither is there.

    A `.conda` is a zstd tarball. Python 3.14 decodes it with `compression.zstd`; older
    versions need the `zstandard` package, which build.sh pip-installs. Both paths exist
    because the manylinux container runs 3.12 while this suite may run on either, and the
    fallback would otherwise be dead code nobody had executed.
    """

    def test_the_stdlib_decoder_is_preferred(self, monkeypatch):
        """On 3.14 no third-party package should be needed at all."""
        pytest.importorskip("compression.zstd", reason="stdlib zstd needs python 3.14")
        monkeypatch.setitem(sys.modules, "zstandard", None)

        assert extract_mod._decompress(_zstd_compress(b"payload")) == b"payload"

    def test_the_zstandard_fallback_is_used_when_the_stdlib_has_none(self, monkeypatch):
        """This is the path the manylinux container's python 3.12 actually takes."""
        zstandard = pytest.importorskip(
            "zstandard", reason="zstandard unavailable on this machine"
        )
        assert zstandard is not None
        real_import = __import__

        def _no_stdlib_zstd(name, *args, **kwargs):
            """Hide `compression.zstd` so the fallback runs."""
            if name == "compression.zstd" or name == "compression":
                raise ImportError("no stdlib zstd")
            return real_import(name, *args, **kwargs)

        monkeypatch.setattr("builtins.__import__", _no_stdlib_zstd)

        assert extract_mod._decompress(_zstd_compress(b"payload")) == b"payload"

    def test_no_decoder_at_all_is_a_clear_failure(self, monkeypatch):
        """The message has to name the remedy; this runs inside a bare container."""
        real_import = __import__

        def _no_zstd(name, *args, **kwargs):
            """Hide both decoders."""
            if name in {"compression", "compression.zstd", "zstandard"}:
                raise ImportError("no zstd")
            return real_import(name, *args, **kwargs)

        monkeypatch.setattr("builtins.__import__", _no_zstd)

        with pytest.raises(SystemExit, match="no zstd decoder"):
            extract_mod._decompress(b"irrelevant")


class TestNonRegularMember:
    """A directory named like the header must not be read as one."""

    def test_a_directory_member_is_refused(self, tmp_path: Path):
        """`extractfile` returns None for a directory, which would crash on `.read()`."""
        inner = io.BytesIO()
        with tarfile.open(fileobj=inner, mode="w") as tf:
            info = tarfile.TarInfo("include/cpl_config.h")
            info.type = tarfile.DIRTYPE
            tf.addfile(info)
        package = tmp_path / "p.conda"
        with zipfile.ZipFile(package, "w") as zf:
            zf.writestr("metadata.json", "{}")
            zf.writestr("pkg-x.tar.zst", _zstd_compress(inner.getvalue()))

        with pytest.raises(SystemExit, match="not a regular file"):
            extract_mod.extract(package, tmp_path / "inc")


class TestCli:
    """The entry point build.sh invokes."""

    def test_it_reports_the_macros_it_checked(self, tmp_path: Path, capsys):
        """The build log should record which ABI facts the header actually declared."""
        package = _conda_package(
            tmp_path / "p.conda", {"include/cpl_config.h": _HEADER}
        )

        code = extract_mod.main(
            ["extract_cpl_config.py", str(package), str(tmp_path / "inc")]
        )

        out = capsys.readouterr().out
        assert code == 0
        assert "SIZEOF_VOIDP 8" in out
        assert "VSI_STAT64_T stat64" in out

    def test_wrong_argument_count_is_a_usage_error(self, tmp_path: Path, capsys):
        """build.sh runs under `set -e`, so the exit code is the signal."""
        code = extract_mod.main(["extract_cpl_config.py", str(tmp_path)])

        assert code == 2
        assert "usage:" in capsys.readouterr().err
